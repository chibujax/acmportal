<p class="text-muted">Track your own attendance record across the year.</p>

<x-docs.step :number="1" image="member/meetings/attendance-1.png" alt="The My Attendance page with stats and chart">
    Go to <strong>My Attendance</strong> in the sidebar. Use the year dropdown to look at a different year. You'll
    see how many meetings you've attended, missed, and your overall attendance rate, plus a month-by-month chart.
</x-docs.step>

<x-docs.step :number="2">
    Below that, every meeting for the selected year is listed with your status —
    <strong>Present</strong>, <strong>Late</strong>, <strong>Excused</strong>, or <strong>Absent</strong> — and
    your exact check-in time where applicable.
</x-docs.step>
