<p class="text-muted">Published meeting minutes are available to every member.</p>

<x-docs.step :number="1" image="member/meetings/minutes-1.png" alt="The list of published meeting minutes">
    Go to <strong>Meeting Minutes</strong> in the sidebar. Recently published minutes are marked with a
    <strong>New</strong> badge.
</x-docs.step>

<x-docs.step :number="2">
    Select <strong>View</strong> to open a minutes record.
</x-docs.step>

<x-docs.step :number="3" image="member/meetings/minutes-2.png" alt="An individual minutes record with View and Download buttons">
    From here you can <strong>View</strong> the PDF in your browser or device's PDF viewer, or
    <strong>Download</strong> it to keep a copy.
</x-docs.step>
