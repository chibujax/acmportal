<p class="text-muted">Keep a family record of your children alongside your own member profile.</p>

<x-docs.step :number="1" image="member/profile-and-family/children-1.png" alt="The Children section with the Add Child form expanded">
    On the <strong>Family & Relationships</strong> page, select <strong>Add Child</strong> to expand the form.
</x-docs.step>

<x-docs.step :number="2">
    Enter their first and last name (required); date of birth, gender, and notes are optional. Choose whether
    you're recorded as <strong>Father</strong> or <strong>Mother</strong> — if you have a linked spouse, they're
    automatically added as the other parent.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Save Child</strong>. The child now appears in the list below, visible to both parents if you're
    linked as spouses.
</x-docs.step>

<x-docs.step :number="4">
    To remove a record, select the trash icon on that child's card and confirm.
</x-docs.step>
