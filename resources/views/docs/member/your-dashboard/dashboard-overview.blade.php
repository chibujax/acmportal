<p class="text-muted">Your dashboard is the first thing you see after signing in — a snapshot of where you stand.</p>

<x-docs.step :number="1" image="member/your-dashboard/dashboard-1.png" alt="The member dashboard stat cards">
    Four cards across the top summarise your account: <strong>Total Paid</strong>, how many dues
    cycles/levies are currently <strong>Active</strong>, your <strong>Outstanding</strong> balance, and your
    <strong>Missed Attendance</strong> counts. Select the outstanding card to see a full breakdown by cycle.
</x-docs.step>

<x-docs.step :number="2">
    <strong>Active Dues & Levies</strong> lists everything currently open for you to pay or pledge towards, with a
    progress bar showing how much of each you've settled. This is also where <strong>Pay by Card</strong> and
    <strong>Pledge Now</strong> buttons appear when relevant.
</x-docs.step>

<x-docs.step :number="3">
    <strong>Recent Payments</strong> on the right shows your last few payments — select <strong>All</strong> to see
    your full history.
</x-docs.step>

<div class="alert alert-light border small mt-3">
    <strong>Banners you might see:</strong> a prompt to verify or add your email, a green banner if a meeting is
    live right now (with a one-tap <strong>Join Meeting</strong> button), and a notice when new minutes are
    published.
</div>
