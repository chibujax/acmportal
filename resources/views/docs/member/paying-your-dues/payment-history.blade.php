<p class="text-muted">A full record of every payment linked to your account.</p>

<x-docs.step :number="1" image="member/paying-your-dues/history-1.png" alt="The payment history table">
    Go to <strong>Payment History</strong> in the sidebar (or select <strong>All</strong> from the Recent Payments
    panel on your dashboard). Each row shows the receipt number, which dues cycle it applied to, the amount,
    payment method, date, and status.
</x-docs.step>

<x-docs.step :number="2">
    A <strong>Completed</strong> badge means the payment has been fully processed; <strong>Pending</strong> or
    <strong>Failed</strong> reflect payments still processing or that didn't go through — these won't count towards
    your outstanding balance until completed.
</x-docs.step>
