<p class="text-muted">
    Some dues cycles are pledge-based free-will donations (e.g. a harvest offering) rather than a fixed amount.
</p>

<x-docs.step :number="1" image="member/paying-your-dues/pledge-1.png" alt="The pledge form on the dashboard">
    On your dashboard, find the levy under <strong>Active Dues & Levies</strong>. If it accepts pledges and you
    haven't made one yet, you'll see an amount field right there — no separate page needed.
</x-docs.step>

<x-docs.step :number="2">
    Enter the amount you're pledging. If you have a linked spouse, tick <strong>On behalf of my family</strong> to
    pledge for both of you together.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Pledge Now</strong>. The panel updates to show your pledge and how much of it you've fulfilled
    so far — you can pay towards it at any time the same way you'd pay any other due.
</x-docs.step>
