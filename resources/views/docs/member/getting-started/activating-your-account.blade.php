<p class="text-muted">
    If an admin invited you directly (rather than you finding your own way in through Join), you'll receive a link
    by SMS or email. Use these steps once you open it.
</p>

<x-docs.step :number="1" image="member/getting-started/activate-1.png" alt="The account activation page with a welcome message">
    Open the activation link. You'll see a welcome message with your name already on it, confirming the link is
    valid.
</x-docs.step>

<x-docs.step :number="2">
    Choose a password — at least 10 characters, including a letter and a number — and enter it again to confirm.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Activate My Account</strong>. You'll be signed in automatically and taken straight to your
    dashboard.
</x-docs.step>

<x-docs.step :number="4" image="member/getting-started/activate-expired.png" alt="The expired or invalid activation link message">
    If the link has already been used or has expired, you'll see a notice to that effect instead — contact your
    admin to request a new invite.
</x-docs.step>
