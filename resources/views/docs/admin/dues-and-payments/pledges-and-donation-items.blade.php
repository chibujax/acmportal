<p class="text-muted">For a pledge-based cycle, use this page to record what each member (or an outside donor) has committed and given.</p>

<x-docs.step :number="1">
    From a pledge-based cycle's detail page, select <strong>Manage Pledges</strong>.
</x-docs.step>

<x-docs.step :number="2" image="admin/dues-and-payments/pledges-1.png" alt="The record contribution form">
    Search for the member, or tick <strong>Anonymous / non-member donor</strong> to log a gift that isn't tied to a
    member account (e.g. a visitor).
</x-docs.step>

<x-docs.step :number="3">
    Enter a <strong>Pledge Amount</strong> if they're committing money — this updates their existing pledge if one's
    already on record. Tick <strong>Shared with spouse</strong> if the pledge counts for both partners.
</x-docs.step>

<x-docs.step :number="4">
    If the cycle accepts item donations, select <strong>Add Item</strong> to log physical contributions (type,
    quantity, description, estimated value) alongside or instead of a money pledge.
</x-docs.step>

<x-docs.step :number="5" image="admin/dues-and-payments/pledges-2.png" alt="The pledges and items summary tables">
    Select <strong>Save Contribution</strong>. The right-hand side shows every pledge and item on record, with
    balances and a <strong>Redeem</strong> button to mark an item as received (in full or partially).
</x-docs.step>
