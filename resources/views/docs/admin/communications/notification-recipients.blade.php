<p class="text-muted">These are the people notified when the portal's automated background jobs run — not members, but whoever needs to know if something needs attention.</p>

<x-docs.step :number="1" image="admin/communications/recipients-1.png" alt="The add recipient form and current recipients list">
    Go to <strong>Alert Recipients</strong> in the sidebar. Add a name plus at least an email or phone number.
</x-docs.step>

<x-docs.step :number="2">
    These recipients are notified by the monthly automated job that flags consecutive absentees, so the right
    person always sees it even if nobody happens to check the portal that day.
</x-docs.step>

<x-docs.step :number="3">
    Use the toggle to temporarily disable a recipient without deleting them, or remove them entirely.
</x-docs.step>
