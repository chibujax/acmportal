<p class="text-muted">Surface members who've missed several meetings in a row, so they can be followed up with before it becomes a pattern.</p>

<x-docs.step :number="1" image="admin/meetings-and-attendance/absentees-1.png" alt="The consecutive absentees list">
    Go to <strong>Consecutive Absentees</strong> in the sidebar. The list shows members who've missed the last few
    meetings in a row — how many meetings counts as "consecutive" is configurable. Members who joined too recently
    to have missed that many are automatically excluded.
</x-docs.step>

<x-docs.step :number="2">
    Select <strong>Export</strong> for a CSV, or use the SMS/email option to message everyone on the list directly
    from this page — it's logged to the Contact Log automatically.
</x-docs.step>
