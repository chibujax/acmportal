<p class="text-muted">Upload and publish PDF minutes for members to view or download.</p>

<x-docs.step :number="1" image="admin/meetings-and-attendance/minutes-1.png" alt="The upload meeting minutes form">
    Go to <strong>Meeting Minutes</strong> in the sidebar and select the upload/new button. Enter a title and the
    meeting date, then attach the PDF file (up to 10MB).
</x-docs.step>

<x-docs.step :number="2">
    Tick <strong>Publish immediately</strong> to make it visible to members right away, or leave it unticked to
    save as a draft first.
</x-docs.step>

<x-docs.step :number="3">
    From the minutes list, use <strong>Publish</strong> / <strong>Unpublish</strong> to control visibility at any
    time, or edit the title, date, or replace the file entirely.
</x-docs.step>
