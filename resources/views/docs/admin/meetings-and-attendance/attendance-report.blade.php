<p class="text-muted">Yearly attendance statistics for every member — this can be granted separately from full Meeting Management.</p>

<x-docs.step :number="1" image="admin/meetings-and-attendance/report-1.png" alt="The attendance report table and chart">
    Go to <strong>Attendance Report</strong> in the sidebar. Each member shows their meetings attended, total
    meetings held, and attendance percentage for the selected year, alongside a monthly chart.
</x-docs.step>

<x-docs.step :number="2">
    Members below the 70% eligibility threshold are highlighted, making it easy to see who may need a follow-up.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Export</strong> to download the report as a CSV.
</x-docs.step>
