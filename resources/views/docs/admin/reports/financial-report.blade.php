<p class="text-muted">The most detailed financial view — collections broken down however you need to see them.</p>

<x-docs.step :number="1" image="admin/reports/financial-1.png" alt="The financial report with year/cycle/legacy mode selector">
    Go to <strong>Financial Report</strong> in the sidebar. Choose how to view it: by <strong>year</strong> (every
    cycle in that year combined), a <strong>specific cycle</strong> (fixed-amount or pledge-based), or
    <strong>legacy</strong> mode (pre-2026 carryover debt only).
</x-docs.step>

<x-docs.step :number="2">
    The report gives both a per-member breakdown (who paid what) and a per-transaction breakdown (every individual
    payment), sortable and searchable.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Export</strong> for a CSV, or <strong>Print / PDF</strong> for a clean printable version with
    every row shown (not just the current page).
</x-docs.step>
