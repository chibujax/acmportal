<p class="text-muted">Spot members who may be drifting away — before it's obvious.</p>

<x-docs.step :number="1" image="admin/reports/engagement-1.png" alt="The member engagement report">
    Go to <strong>Member Engagement</strong> in the sidebar. Each row shows a member's last meeting attended and
    last dues payment, so members who haven't engaged in a while stand out.
</x-docs.step>

<x-docs.step :number="2">
    Search by name and sort by either date to focus on whoever's been quiet the longest.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Export</strong> for a CSV.
</x-docs.step>
