<p class="text-muted">See exactly who still owes money on a given dues cycle.</p>

<x-docs.step :number="1" image="admin/reports/arrears-1.png" alt="The arrears report filtered by dues cycle">
    Go to <strong>Arrears</strong> in the sidebar and choose a dues cycle from the dropdown.
</x-docs.step>

<x-docs.step :number="2">
    The list shows every member with an outstanding balance on that cycle, sortable by name or amount owed.
</x-docs.step>

<x-docs.step :number="3">
    Select <strong>Export</strong> for a CSV, or print a clean copy for a meeting.
</x-docs.step>
